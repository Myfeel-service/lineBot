/**
 * 「AI 建議補的知識」一開始就不列的那一種：客人在問**他自己那一筆**的訂單／付款／出貨／退款狀態（`C-318`，2026-10-15 拍板 `D-126`④）。
 *
 * 為什麼：這種問題要真人去查那一筆，補一條知識答不了——「請問這張訂單的付款狀態是？」寫什麼都不對。
 * MYFEEL 36 筆建議只採用 2、忽略 28，清單上混著這種題目，店家每次都要自己判斷一次「這不是知識」。
 *
 * ⚠️ 這支跟 ai-answer 的 `mentionsOwnOrder` **刻意不是同一份**：那支決定「要不要轉真人」，
 *    寧可多轉（線索從寬，裸的「我買的」「處理中」都算）；這支決定「要不要把一個知識缺口藏起來」，
 *    藏錯＝店家永遠看不到一個真缺口（例「我買的鍋子有瑕疵怎麼退」是退換貨規則，補一條就答得出來）。
 *    所以這裡從嚴：要同時看得出「他那一筆」＋「在問狀態」，或是講得出「等了多久還沒有消息」的催單。
 * ⛔ 改規則前先跑測試裡的正式站例句（MYFEEL）：要擋的、不能擋的各一串，兩邊都要過。
 */

/** 指涉他自己那一筆（講得出號碼、「這筆／這張訂單」、已經下單／付款／申請過） */
const OWN_REF_RE = new RegExp([
  '單號|訂單編號|訂單號碼|物流編號|貨運單號|追蹤號碼|提單號',
  '這張訂單|這份訂單|這個訂單|這筆|這一筆|那筆|那一筆|這張單|我這張|我這筆|上一筆',
  '我的訂單|我下的單|我訂的|我買的|我付的|我匯的|我的貨|我的包裹|我的退款|我的退貨|我寄回',
  '已經?下單|已經?下訂|已經?付款|已經?匯款|已經?寄回|已經?退回|已經?申請',
].join('|'))

/** 跟訂單有關的名詞：「我買的除濕機燈號狀態」有「我買的」＋「狀態」，但講的是機器，不是那一筆訂單 */
const ORDER_NOUN_RE = /訂單|訂購|付款|匯款|款項|出貨|發貨|寄出|寄送|配送|物流|包裹|貨運|到貨|退款|退費|退貨|取消|單號/

/** 在問那一筆現在怎麼樣了 */
const STATUS_ASK_RE = new RegExp([
  '狀態|進度|處理狀況',
  '完成了嗎|好了嗎|成功了嗎|處理好了嗎|是否已|有沒有成功',
  '到哪|寄了嗎|寄出了嗎|出貨了嗎|發貨了嗎|到貨了嗎|收到了嗎|有收到嗎|退了嗎|退款了嗎',
  '(什麼時候|何時|多久)(會|才|可以|能)?(出貨|發貨|寄|到貨|收到|退款|退費|入帳)',
  '被取消|取消了|還沒|遲遲',
].join('|'))

/**
 * 不用看是哪一筆也知道是在查單：訂單／付款／退款的「狀態、進度」。
 * ⛔ 刻意不放「出貨進度」：募資、預購常有一大群人問「出貨進度？」，答案是一則公告（「10 月底依訂單順序出貨」），
 *    補一條知識正好救得了——那一句要有「這筆／我的」才算查單（走上面那條）。
 */
const STRONG_STATUS_RE = /(訂單|付款|匯款|退款|退費|退貨|取消)(的)?(狀態|進度|處理進度|處理狀況)/

/** 催單：問「有消息嗎」＋講得出等了多久（「從一開始反應到現在都過半年了」） */
const CHASE_RE = /有(任何)?(消息|進度|下文|回覆|回音|結果)(了)?嗎|(處理|進行)得(如何|怎樣|怎麼樣)|怎麼樣了/
const ELAPSED_RE = /到現在|至今|半年|等了|等很久|多久了|一直|都沒|還是沒|過了?.{0,4}(天|週|周|禮拜|星期|個月|年)/

/** 抱怨那一筆沒動：「怎麼還沒收到」「到現在還沒出貨」「遲遲沒有退款」 */
const COMPLAINT_RE = /(怎麼|為什麼|為何|到現在|至今|遲遲|一直)(都)?(還)?(沒|未)(有)?(收到|出貨|發貨|寄|到貨|送到|退款|退費|入帳|處理|回覆|消息)|還(沒|未)(有)?(收到|出貨|發貨|寄出|到貨|退款|退費|入帳)/

/** 問「怎麼查／在哪看」＝問規則，知識答得出來（「如何知道我的發票號碼」） */
const HOWTO_RE = /(怎麼|如何|哪裡|在哪|去哪|要去哪)(裡)?(查|看|確認|知道|追蹤|查詢|申請|退|取消)/
/** 問「可不可以」＝問規則（「這筆訂單可以取消嗎」：取消的方法寫得出一條） */
const POLICY_ASK_RE = /(可以|能不能|能否|可否|可不可以|是否可以|能)(取消|退|換|改)/
/** 假設語氣＝還沒發生，問的是規則（「如果還沒收到可以退款嗎」） */
const HYPOTHETICAL_RE = /如果|假如|萬一|若是|的話/

/**
 * 這一句是不是在查他自己那一筆的訂單／付款／出貨／退款狀態。
 * 拿不準的一律回 false（＝照舊列出來）：漏擋只是清單上多一題，擋錯是缺口不見了。
 */
export function isPersonalOrderQuery(raw: string): boolean {
  const q = String(raw ?? '').replace(/\s+/g, '')
  if (!q) return false
  if (HOWTO_RE.test(q) || POLICY_ASK_RE.test(q) || HYPOTHETICAL_RE.test(q)) return false
  if (STRONG_STATUS_RE.test(q)) return true
  if (CHASE_RE.test(q) && ELAPSED_RE.test(q)) return true
  if (COMPLAINT_RE.test(q)) return true
  return OWN_REF_RE.test(q) && ORDER_NOUN_RE.test(q) && STATUS_ASK_RE.test(q)
}

/**
 * 一組問題是不是「查單」那一種：**超過一半**的題目是才算（照題數算、不照次數）。
 *
 * 為什麼照題數：一組裡 1 題查單被問 5 次、2 題一般問題各 1 次——照次數算會整組藏掉，
 * 那兩題一般問題就跟著不見了。照題數算，這組照樣列出來。
 */
export function isPersonalOrderGroup(queries: readonly string[] | undefined | null): boolean {
  const list = (queries ?? []).map(q => String(q ?? '').trim()).filter(Boolean)
  if (!list.length) return false
  const personal = list.filter(isPersonalOrderQuery).length
  return personal * 2 > list.length
}
