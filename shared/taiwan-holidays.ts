/** 表上最後涵蓋到哪一天（不是最後一個假日——12 月底之後沒有假日也算「查過了」） */
export const TAIWAN_HOLIDAYS_COVERED_UNTIL = '2027-12-31'

const BY_DATE = new Map(TAIWAN_HOLIDAYS.map(h => [h.date, h.name]))

/** 這一天是不是國定放假日；是就回名稱，不是回 `null` */
export function taiwanHolidayName(dateKey: string): string | null {
  return BY_DATE.get(dateKey) ?? null
}

/**
 * 從某天（含）起的下一個國定放假日；表上沒有了回 `null`。
 * @param opts.skipWeekends 週末本來就休的店：落在週末的假日對他沒差（2026-10-25 週日光復節），講補假那天才有用
 */
export function nextTaiwanHoliday(fromKey: string, opts: { skipWeekends?: boolean } = {}): TaiwanHoliday | null {
  return TAIWAN_HOLIDAYS.find((h) => {
    if (h.date < fromKey) return false
    if (!opts.skipWeekends) return true
    const dow = new Date(`${h.date}T00:00:00Z`).getUTCDay()
    return dow !== 0 && dow !== 6
  }) ?? null
}
