// ═══════════════════════════════════════════════════════════════════
//  用量單位的單一事實來源：「次」「則」「場」各是什麼
//
//  這三個量詞散落在十幾個畫面，飄一次就要付代價：2026-08-11 老闆在
//  「超管 → 官方帳號管理」看到「235 則」、在「成本總覽」看到
//  「呼叫 AI 235 次（答出 95 則）」——同一個 235 兩種量詞，
//  等於畫面在說謊（真正的則數是 95，差 2.5 倍）。
//
//  對應到 aiUsage 月結桶（server/utils/ai-usage.ts）的欄位：
//    · invocations     → **次**  客人每來一則訊息，AI 就被叫起來一次
//                                （答出／轉真人／反問／跳過都算）
//    · billable        → **則**  **收錢與額度攔截的單位**＝答出 ＋ 反問（`D-69`）
//    · answered        → 品質指標「AI 自己答完了嗎」，**不是**計費單位
//    · testInvocations → **次**  後台自用：試打、小幫手、試答、生成腳本
//    · 對話統計 session → **場**  一整段對話（見 conversation-stats / ai-usage 表現區）
//
//  規則：畫面上任何一個數字，旁邊的量詞都要能對回上面某一欄。
//  ⛔ 別把 invocations 掛「則」——會被讀成計費則數（實際差 2～3 倍）。
//  ⛔ 也別拿 answered 當成本分母——那筆錢買的是全部呼叫，answered 只佔約四成。
//  ⛔ 2026-09-07 起 answered ≠ 則：計費看 billable。畫面要講「扣幾則」時別再讀 answered。
// ═══════════════════════════════════════════════════════════════════

