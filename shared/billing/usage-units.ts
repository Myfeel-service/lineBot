export const REPLY_UNIT_TIP = '1 則＝AI 出手回答一次：自動發送給客人，或草稿模式下擬好給客服參考；AI 為了問清楚需求而反問的那句也算一則。「答不出來、轉真人」以及「跟本店無關、AI 婉拒」的那句不扣額度。一次回答就算拆成好幾則訊息送出，仍然只算一則。跟 LINE 官方帳號方案的「訊息則數」是兩回事，互不相干。'

