export const CALL_UNIT_TIP = '1 次＝AI 被叫起來一次：客人每來一則訊息就算一次，不論最後是答出來、轉真人還是反問。成本按「次」算；額度與計費按「則」算（答出來的與反問的才扣，轉真人不扣），所以「次」一定大於等於「則」。'

