// ── 「AI 知識量放滿了」的共用零件（`C-477`，2026-11-11）──────────────────────────
//
// ⛔ **整句不要共用**：加入視窗門口要講「新的資料整理完會放不進去」、一次傳好幾份要講「收了前 N 條、
//    還有 M 條沒收」、網站草稿要講「這裡的還沒算進去，刪掉它們空不出位子」——那些只有那一頁成立，
